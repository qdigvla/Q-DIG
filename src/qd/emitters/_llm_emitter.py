"""Base LLM emitter class"""

import json
import logging
from typing import Dict, List

import numpy as np
import torch
from ribs.archives import ArchiveBase
from ribs.emitters._emitter_base import EmitterBase

from src.model.huggingface import BaseLLM

logger = logging.getLogger(__name__)


class LLMEmitterBase(EmitterBase):
    """Base LLM emitter class"""

    def __init__(
        self,
        llm: BaseLLM,
        archive: ArchiveBase,
        batch_size: int,
        solution_dim: int,
        initial_solutions: List[Dict],
        measure_cfg: Dict,
        bounds=None,
        seed=None,
    ):
        self._batch_size = batch_size
        self._rng = np.random.default_rng(seed)

        self._initial_solutions = initial_solutions  # list(initial_solutions)
        self._measure_cfg = measure_cfg

        self.llm = llm

        if bounds is not None:
            raise ValueError("Bounds not supported for this emitter")

        EmitterBase.__init__(
            self,
            archive,
            solution_dim=solution_dim,
            bounds=bounds,
        )

        self._device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

        self._prompts = []  # stored prompts for the current batch

    @property
    def batch_size(self):
        return self._batch_size

    def _random_sample(
        self,
        num_samples: int,
        archive_sample_rate: float = 1,
        initial_solution_sample_key: str = "prompt",
    ):
        """Randomly samples 'num_samples' solutions. Each solution contains `solution_dim` prompts."""

        if self._archive.empty:
            logging.warning(
                "Archive is empty. Randomly sampling solutions from initial solutions."
            )
            # TODO: debug below
            # sols = self._rng.choice(self._initial_solutions, size=num_samples, replace=True)
            # sols = [sol[initial_solution_sample_key] for sol in sols]

            # fall back to just repeating the first initial solution, since the archive
            # has nothing to sample elites from yet
            sols = [
                self._initial_solutions[0][initial_solution_sample_key]
                for _ in range(num_samples)
            ]

            return sols
        else:
            # per sample, flip a coin weighted by archive_sample_rate: with probability
            # archive_sample_rate draw an elite from the archive, otherwise fall back to
            # the first initial solution. This lets callers control how much of the
            # mutation batch is based on existing archive elites vs. the seed task.
            elites = [
                (
                    self._initial_solutions[0][
                        initial_solution_sample_key
                    ]  # self._rng.choice(self._initial_solutions, size=1)[initial_solution_sample_key]
                    if self._rng.random() > archive_sample_rate
                    else self._archive.sample_elites(1)["solution"][0][0]
                )
                for _ in range(num_samples)
            ]
            return elites

    def ask(self):
        raise NotImplementedError("Ask method not implemented for base LLM emitters")

    def tell(self, solution, objective, measures, add_info, **fields):
        """tell the emitter the solution and its objectve values

        Args:
            solution (numpy.ndarray): Array of solutions generated by this
                emitter's :meth:`ask()` method.
            objective (numpy.ndarray): 1D array containing the objective
                function value of each solution.
            measures (numpy.ndarray): ``(n, <measure space dimension>)`` array
                with the measure space coordinates of each solution.
            add_info (dict): Data returned from the archive
                :meth:`~ribs.archives.ArchiveBase.add` method.
            fields (keyword arguments): Additional data for each solution. Each
                argument should be an array with batch_size as the first
                dimension.
        """
        raise NotImplementedError("Tell method not implemented for LLM emitters")
